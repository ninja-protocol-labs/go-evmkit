type zksyncNetwork struct {
	name      string
	client    *Client
	address   string
	blockHash string
	txHash    string
}

type ZkSyncRPCSuite struct {
	suite.Suite

	Enable bool

	ctx    context.Context
	cancel context.CancelFunc

	mainnet zksyncNetwork
	testnet zksyncNetwork
}

func TestZkSyncRPCSuite(t *testing.T) {
	suite.Run(t, &ZkSyncRPCSuite{
		Enable: false,
	})
}

func (s *ZkSyncRPCSuite) SetupSuite() {
	if !s.Enable && !GlobalEnable {
		s.T().Skip("disabled")
	}

	s.ctx, s.cancel = context.WithTimeout(context.Background(), 60*time.Second)

	s.mainnet = zksyncNetwork{
		name:      "mainnet",
		client:    NewClient("https://mainnet.era.zksync.io", WithTimeout(15*time.Second)),
		blockHash: "0xf1e7c64415794550d778655f5b0c282c98f5150612966340725c853c8a653e6d",
		txHash:    "0x7eca123aea7e7df58d5d82c2d8416a751adf75630a8ee080db3e971cb82bdff7",
		address:   "0x833e1D0b8Bc979D49d57b65dCF18364694B16D52",
	}
	s.testnet = zksyncNetwork{
		name:      "testnet",
		client:    NewClient("https://sepolia.era.zksync.dev", WithTimeout(15*time.Second)),
		blockHash: "0x90f3d56445b78257bdba47844a940c00efa211ba17b3f5dd4e50314bb329205a",
		txHash:    "0x02739b575e114d2435f98bb55cc18dba12d9fb0f7228c6be468a13689fa73387",
		address:   "0x833e1D0b8Bc979D49d57b65dCF18364694B16D52",
	}
}

func (s *ZkSyncRPCSuite) TearDownSuite() {
	if s.cancel != nil {
		s.cancel()
	}
}

func (s *ZkSyncRPCSuite) networks() []zksyncNetwork {
	return []zksyncNetwork{s.mainnet, s.testnet}
}

func (s *ZkSyncRPCSuite) TestETHChainID() {
	for _, n := range s.networks() {
		var result string
		elems := Elements{ETHChainID(uuid.NewString(), &result)}
		s.Require().NoError(n.client.Batch(s.ctx, elems), n.name)
	}
}

