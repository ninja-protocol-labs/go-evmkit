type celoNetwork struct {
	name      string
	client    *Client
	address   string
	blockHash string
	txHash    string
}

type CeloRPCSuite struct {
	suite.Suite

	Enable bool

	ctx    context.Context
	cancel context.CancelFunc

	mainnet celoNetwork
	testnet celoNetwork
}

func TestCeloRPCSuite(t *testing.T) {
	suite.Run(t, &CeloRPCSuite{
		Enable: false,
	})
}

func (s *CeloRPCSuite) SetupSuite() {
	if !s.Enable && !GlobalEnable {
		s.T().Skip("disabled")
	}

	s.ctx, s.cancel = context.WithTimeout(context.Background(), 60*time.Second)

	s.mainnet = celoNetwork{
		name:      "mainnet",
		client:    NewClient("https://forno.celo.org", WithTimeout(15*time.Second)),
		blockHash: "0x8cfc6cd2e61157d7e9c5b1c64e33af1f8678dfb7838d719d8b1bff1bd8d58338",
		txHash:    "0x6c4412f15d6fb9c11b86ac7f4a0e322d877b99b1b5de712ba263c91d11e3e0ed",
		address:   "0x833e1D0b8Bc979D49d57b65dCF18364694B16D52",
	}
	s.testnet = celoNetwork{
		name:      "testnet",
		client:    NewClient("https://forno.celo-sepolia.celo-testnet.org", WithTimeout(15*time.Second)),
		blockHash: "0x282003cef883a480eba74eb43b5369d2704a8efcb06213088418d0ffba2f5471",
		txHash:    "0xf87c34eee961c08c48d46e8ef2ccdbb2e101642d98d23f1b8bfee579e683a564",
		address:   "0x833e1D0b8Bc979D49d57b65dCF18364694B16D52",
	}
}

func (s *CeloRPCSuite) TearDownSuite() {
	if s.cancel != nil {
		s.cancel()
	}
}

func (s *CeloRPCSuite) networks() []celoNetwork {
	return []celoNetwork{s.mainnet, s.testnet}
}

func (s *CeloRPCSuite) TestETHChainID() {
	for _, n := range s.networks() {
		var result string
		elems := Elements{ETHChainID(uuid.NewString(), &result)}
		s.Require().NoError(n.client.Batch(s.ctx, elems), n.name)
	}
}

