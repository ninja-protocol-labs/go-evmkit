type gnosisNetwork struct {
	name      string
	client    Client
	address   string
	blockHash string
	txHash    string
}

type GnosisRPCSuite struct {
	suite.Suite

	Enable bool

	ctx    context.Context
	cancel context.CancelFunc

	mainnet gnosisNetwork
	testnet gnosisNetwork
}

func TestGnosisRPCSuite(t *testing.T) {
	suite.Run(t, &GnosisRPCSuite{
		Enable: false,
	})
}

func (s *GnosisRPCSuite) SetupSuite() {
	if !s.Enable && !GlobalEnable {
		s.T().Skip("disabled")
	}

	s.ctx, s.cancel = context.WithTimeout(context.Background(), 60*time.Second)

	s.mainnet = gnosisNetwork{
		name:      "mainnet",
		client:    NewClient("https://rpc.gnosischain.com", WithTimeout(15*time.Second)),
		blockHash: "0x103ecd1b5b24e9bfb7dfb6fcadf614df3806feffbbdf80eaa7befd31d5ee8f08",
		txHash:    "0x7929ab8afb1a6c0fb2cfdf875aefe07eb9cdfd84ce86126fe3953e92939abf8f",
		address:   "0x833e1D0b8Bc979D49d57b65dCF18364694B16D52",
	}
	s.testnet = gnosisNetwork{
		name:      "testnet",
		client:    NewClient("https://rpc.chiadochain.net", WithTimeout(15*time.Second)),
		blockHash: "0x7049253e286f092c363e3c84025ba46bb32172395c3acd9da754716debf7d188",
		txHash:    "0xc84b9d5cadc8d859105790ca15376ed8fff20b04621a1eb668f11d94d9d34eb2",
		address:   "0x833e1D0b8Bc979D49d57b65dCF18364694B16D52",
	}
}

func (s *GnosisRPCSuite) TearDownSuite() {
	if s.cancel != nil {
		s.cancel()
	}
}

func (s *GnosisRPCSuite) networks() []gnosisNetwork {
	return []gnosisNetwork{s.mainnet, s.testnet}
}

func (s *GnosisRPCSuite) TestETHChainID() {
	for _, n := range s.networks() {
		var result string
		elems := Elements{ETHChainID(uuid.NewString(), &result)}
		s.Require().NoError(n.client.Batch(s.ctx, elems), n.name)
	}
}

