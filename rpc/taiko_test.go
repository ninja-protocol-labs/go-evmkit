type taikoNetwork struct {
	name      string
	client    *Client
	address   string
	blockHash string
	txHash    string
}

type TaikoRPCSuite struct {
	suite.Suite

	Enable bool

	ctx    context.Context
	cancel context.CancelFunc

	mainnet taikoNetwork
}

func TestTaikoRPCSuite(t *testing.T) {
	suite.Run(t, &TaikoRPCSuite{
		Enable: false,
	})
}

func (s *TaikoRPCSuite) SetupSuite() {
	if !s.Enable && !GlobalEnable {
		s.T().Skip("disabled")
	}

	s.ctx, s.cancel = context.WithTimeout(context.Background(), 60*time.Second)

	s.mainnet = taikoNetwork{
		name:      "mainnet",
		client:    NewClient("https://rpc.mainnet.taiko.xyz", WithTimeout(15*time.Second)),
		blockHash: "0xe9bc6a682b3b9b85a7cd8f15669f34d7794e489ea73bee7332d6a9fcc509e06a",
		txHash:    "0x6187bc74876b9eac49d408d522ffa4123fa20ff269ad2d37ab40e779b28f2b94",
		address:   "0x833e1D0b8Bc979D49d57b65dCF18364694B16D52",
	}
}

func (s *TaikoRPCSuite) TearDownSuite() {
	if s.cancel != nil {
		s.cancel()
	}
}

func (s *TaikoRPCSuite) networks() []taikoNetwork {
	return []taikoNetwork{s.mainnet}
}

func (s *TaikoRPCSuite) TestETHChainID() {
	for _, n := range s.networks() {
		var result string
		elems := Elements{ETHChainID(uuid.NewString(), &result)}
		s.Require().NoError(n.client.Batch(s.ctx, elems), n.name)
	}
}

