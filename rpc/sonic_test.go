type sonicNetwork struct {
	name      string
	client    Client
	address   string
	blockHash string
	txHash    string
}

type SonicRPCSuite struct {
	suite.Suite

	Enable bool

	ctx    context.Context
	cancel context.CancelFunc

	mainnet sonicNetwork
	testnet sonicNetwork
}

func TestSonicRPCSuite(t *testing.T) {
	suite.Run(t, &SonicRPCSuite{
		Enable: false,
	})
}

func (s *SonicRPCSuite) SetupSuite() {
	if !s.Enable && !GlobalEnable {
		s.T().Skip("disabled")
	}

	s.ctx, s.cancel = context.WithTimeout(context.Background(), 60*time.Second)

	s.mainnet = sonicNetwork{
		name:      "mainnet",
		client:    NewClient("https://sonic-rpc.publicnode.com", WithTimeout(15*time.Second)),
		blockHash: "0x0a20b573177281b9cb4c78560ac397c428c017fdc87570f9ca9d6d94e4cd1b47",
		txHash:    "0xe79e403987a1af2b9f9c98582ac38401f2d2b8e4e61a4003c91c503a58b630d0",
		address:   "0x833e1D0b8Bc979D49d57b65dCF18364694B16D52",
	}
	s.testnet = sonicNetwork{
		name:      "testnet",
		client:    NewClient("https://rpc.testnet.soniclabs.com", WithTimeout(15*time.Second)),
		blockHash: "0x9efa1834906c958c37dc4e6221290922bb52d87b555f9106dfe30b4d1f001743",
		txHash:    "0x8ddbafc14200484131d575c73c6d3a965b69a35317bf342f983ab5d6642e8268",
		address:   "0x833e1D0b8Bc979D49d57b65dCF18364694B16D52",
	}
}

func (s *SonicRPCSuite) TearDownSuite() {
	if s.cancel != nil {
		s.cancel()
	}
}

func (s *SonicRPCSuite) networks() []sonicNetwork {
	return []sonicNetwork{s.mainnet, s.testnet}
}

func (s *SonicRPCSuite) TestETHChainID() {
	for _, n := range s.networks() {
		var result string
		elems := Elements{ETHChainID(uuid.NewString(), &result)}
		s.Require().NoError(n.client.Batch(s.ctx, elems), n.name)
	}
}

