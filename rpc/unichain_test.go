type unichainNetwork struct {
	name      string
	client    Client
	address   string
	blockHash string
	txHash    string
}

type UnichainRPCSuite struct {
	suite.Suite

	Enable bool

	ctx    context.Context
	cancel context.CancelFunc

	mainnet unichainNetwork
	testnet unichainNetwork
}

func TestUnichainRPCSuite(t *testing.T) {
	suite.Run(t, &UnichainRPCSuite{
		Enable: false,
	})
}

func (s *UnichainRPCSuite) SetupSuite() {
	if !s.Enable && !GlobalEnable {
		s.T().Skip("disabled")
	}

	s.ctx, s.cancel = context.WithTimeout(context.Background(), 60*time.Second)

	s.mainnet = unichainNetwork{
		name:      "mainnet",
		client:    NewClient("https://mainnet.unichain.org", WithTimeout(15*time.Second)),
		blockHash: "0x6932c2513564d4bb5523adb3c9063031fdc1d98bcca7e40d4b0929a080707189",
		txHash:    "0xbb363ac366758a34ea95a1a4aab112c2c4ef3a3224087bf5138f56b63952fad8",
		address:   "0x833e1D0b8Bc979D49d57b65dCF18364694B16D52",
	}
	s.testnet = unichainNetwork{
		name:      "testnet",
		client:    NewClient("https://sepolia.unichain.org", WithTimeout(15*time.Second)),
		blockHash: "0xbfc0ead19ca06ac170a0d1cc0caf133ed67824c68b26a185f82e17a50c335060",
		txHash:    "0x26422a7cb166703cb25c7d45a73681d028f8ea1f8dc09fd5bdd88846e5ef18ec",
		address:   "0x833e1D0b8Bc979D49d57b65dCF18364694B16D52",
	}
}

func (s *UnichainRPCSuite) TearDownSuite() {
	if s.cancel != nil {
		s.cancel()
	}
}

func (s *UnichainRPCSuite) networks() []unichainNetwork {
	return []unichainNetwork{s.mainnet, s.testnet}
}

func (s *UnichainRPCSuite) TestETHChainID() {
	for _, n := range s.networks() {
		var result string
		elems := Elements{ETHChainID(uuid.NewString(), &result)}
		s.Require().NoError(n.client.Batch(s.ctx, elems), n.name)
	}
}

