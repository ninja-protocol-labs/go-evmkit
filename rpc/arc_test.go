type arcNetwork struct {
	name      string
	client    *Client
	address   string
	blockHash string
	txHash    string
}

type ArcRPCSuite struct {
	suite.Suite

	Enable bool

	ctx    context.Context
	cancel context.CancelFunc

	mainnet arcNetwork
	testnet arcNetwork
}

func TestArcRPCSuite(t *testing.T) {
	suite.Run(t, &ArcRPCSuite{
		Enable: false,
	})
}

func (s *ArcRPCSuite) SetupSuite() {
	if !s.Enable && !GlobalEnable {
		s.T().Skip("disabled")
	}

	s.ctx, s.cancel = context.WithTimeout(context.Background(), 60*time.Second)

	s.mainnet = arcNetwork{
		name:      "mainnet",
		client:    NewClient("https://rpc.mainnet.arc.io", WithTimeout(15*time.Second)),
		blockHash: "0x1c1eabb17eb449e388990ed3c771488a50509e08230d2407f2719efcdd029092",
		txHash:    "0xbcd6ad5ab47455ef5542ac468a757ce25f21ec4d0ff3866b7fafa1ae76e649f4",
		address:   "0x833e1D0b8Bc979D49d57b65dCF18364694B16D52",
	}
	s.testnet = arcNetwork{
		name:      "testnet",
		client:    NewClient("https://rpc.testnet.arc.io", WithTimeout(15*time.Second)),
		blockHash: "0x501051c391b85c7466da708f890c54c443f667103669e87465fcda32ad4d3f95",
		txHash:    "0x091d822436e68e19d9dcac33b1df5925035d92191b6cc170b6dd93e7152a4873",
		address:   "0x833e1D0b8Bc979D49d57b65dCF18364694B16D52",
	}
}

func (s *ArcRPCSuite) TearDownSuite() {
	if s.cancel != nil {
		s.cancel()
	}
}

func (s *ArcRPCSuite) networks() []arcNetwork {
	return []arcNetwork{s.mainnet, s.testnet}
}

func (s *ArcRPCSuite) TestETHChainID() {
	for _, n := range s.networks() {
		var result string
		elems := Elements{ETHChainID(uuid.NewString(), &result)}
		s.Require().NoError(n.client.Batch(s.ctx, elems), n.name)
	}
}

